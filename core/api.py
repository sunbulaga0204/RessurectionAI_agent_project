# ── Lifespan Context ──────────────────────────────────────────

@asynccontextmanager
async def lifespan(app: FastAPI):
    """
    FastAPI Lifespan manager.
    - Pre-warms/connects the active Vector database (ChromaDB or PostgreSQL).
    - Spawns a background cooperative loop acting as an hourly scheduler 
      to dispatch daily motivation reminders/broadcasts (e.g. at 08:00 AM local).
    """
    store_type = config.VECTOR_STORE_TYPE.capitalize()
    print(f"\n🗄️  Initializing {store_type} Vector Store...")
    vector_store.initialize()

    # ── Start Hourly Broadcast Scheduler Loop ─────────────────────
    async def scheduler_loop():
        """
        Background hourly worker that triggers the motivation broadcast script.
        Checks once per hour to find users whose timezone-adjusted time matches 08:00 AM.
        """
        from broadcast_motivation import run_broadcast_for_hour
        
        print(f"⏰ Scheduler: Active (Checking hourly for 08:00 AM local time delivery).")
        while True:
            now = datetime.datetime.now(datetime.timezone.utc)
            # Hand off the logic to broadcast_motivation to resolve local user timezones
            try:
                await run_broadcast_for_hour(now.hour)
            except Exception as e:
                logger.error(f"Scheduler Error: {e}")
            
            # Sleep for 1 hour
            await asyncio.sleep(3600)

    # Schedule non-blocking execution inside the async event loop
    asyncio.create_task(scheduler_loop())
    
    yield
    print("\n👋 Resurrection Agent shutting down...")


