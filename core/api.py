# ── Pydantic Request / Response Validation Models ─────────────

class ChatRequest(BaseModel):
    """Schema validating incoming message inquiries."""
    query: str = Field(..., description="The user's query or message.")
    system_prompt: str = Field(..., description="System instructions enforcing the persona's voice and boundaries.")
    death_date_ah: str = Field(..., description="Historical death date (AH) used to construct/detect anachronisms.")
    session_id: Optional[str] = Field(None, description="UUID or identifier for chat context persistence.")
    language: str = Field("EN", description="Primary preferred language of the conversation.")
    timezone: int = Field(7, description="Timezone offset (UTC offset) for time-aware triggers.")


class Citation(BaseModel):
    """Grounding citation schema showing document mapping."""
    book: str = ""
    volume: str = ""      # e.g., "Vol. 1" for multi-volume classics like the Ihya'
    chapter: str = ""     # Sub-section title/identifier if available
    page_number: str = "" # Page reference of the source text
    quote: str = ""       # Precise text extract from the historical source

    @classmethod
    def from_llm(cls, data: dict) -> "Citation":
        """Construct from LLM output dictionaries, coercing None fields to empty strings."""
        return cls(
            book=data.get("book") or "",
            volume=str(data.get("volume") or ""),
            chapter=data.get("chapter") or "",
            page_number=str(data.get("page_number") or ""),
            quote=data.get("quote") or "",
        )


class ChatResponse(BaseModel):
    """Strictly typed response returning generation output and validation telemetry."""
    answer_text: str = Field(..., description="The main content generated by the persona.")
    can_answer: bool = Field(..., description="Indicates if the query was successfully grounded in classical text.")
    citations: list[Citation] = Field(default_factory=list, description="Grounding source citations.")
    follow_up: str = Field("", description="Conversation continuation prompt in persona's voice.")
    closing: str = Field("", description="Persona signature or closing blessing.")
    session_id: str = Field("", description="The persistent session context key.")
    persona_name: str = Field("", description="Name of the persona currently answering.")


class ExportRequest(BaseModel):
    """Schema validating request to export chat history."""
    session_id: str = Field(..., description="The context session key to serialize.")
    format: str = Field("json", description="Desired export layout ('json' or 'markdown').")


class SubscriptionRequest(BaseModel):
    """Schema managing daily motivation scheduler registrations."""
    chat_id: str = Field(..., description="Telegram Chat ID or unique subscription key.")
    status: bool = Field(..., description="True to subscribe, False to opt-out.")


