@app.post("/api/v1/{tenant_id}/chat", response_model=ChatResponse)
async def chat(tenant_id: str, req: ChatRequest):
    """
    SaaS Chat processing endpoint. Coordinates RAG intent routing, contextual retrieval,
    knowledge grounding, anachronism protection, and generation.

    Execution Flow:
      1. Fetch/Create persistent memory context scoped by tenant.
      2. Autoregisters numerical sessions (Telegram IDs) for time-aware motivations.
      3. Intent Routing -> Determing if conversational chat vs thematic query.
      4a. Fast Path (requires_rag=False) -> Skip retrieval & verifier, generate conversational reply.
      4b. RAG Path (requires_rag=True) -> Embed search query, execute multi-layer/broad index scan.
      5. Grounding Verification -> Validate responses to block hallucinations or anachronisms.
    """
    # ── 1. Scoped Session Persistence ─────────────────────────────
    session_id = session_manager.get_or_create_session(tenant_id, req.session_id)
    history = session_manager.get_history(session_id)

    # ── 2. Automatic Subscriber Registration ──────────────────────
    # Auto-registers numerical session IDs (typical Telegram chat IDs) for notifications
    if req.session_id and req.session_id.isdigit():
        try:
            vector_store.register_user(tenant_id, req.session_id, req.language, req.timezone)
        except Exception as e:
            logger.warning(f"Failed to register user: {e}")

    try:
        # ── 3. Intent Routing Analysis ────────────────────────────
        # Fast model routes query into casual conversation vs complex domain extraction
        router_output = llm_client.analyze_intent(req.query, history)
        intent = router_output.get("intent", "general_question")
        requires_rag = router_output.get("requires_rag", True)
        search_query = router_output.get("search_string", req.query)

        # ── 4a. Casual Fast Path (No Retrieval, No Grounding check) 
        if not requires_rag:
            print(f"  ⚡ Casual fast path: intent='{intent}' — skipping RAG and Verifier")
            result = llm_client.generate_answer(
                req.query,
                retrieved_chunks=[],        # Casual chat does not require source documents
                system_prompt=req.system_prompt,
                conversation_history=history,
                intent=intent,
            )
            # Add turns to memory and perform routine TTL garbage cleanup
            session_manager.add_turn(session_id, "user", req.query)
            session_manager.add_turn(session_id, "assistant", result.get("answer_text", ""))
            session_manager.cleanup_expired()
            return ChatResponse(
                answer_text=result.get("answer_text", ""),
                can_answer=result.get("can_answer", True),
                citations=[],
                follow_up=result.get("follow_up", ""),
                closing=result.get("closing", ""),
                session_id=session_id,
            )

        # ── 4b. RAG Path: Domain Grounded Generation ──────────────────
        # Check tenant database status before committing resources to retrieval
        if not vector_store.is_ingested(tenant_id):
            return ChatResponse(
                answer_text="No source texts have been linked to this persona. The administrator needs to run the ingestion script.",
                can_answer=False,
                session_id=session_id,
            )

        # Evaluate query length. Complex keywords/longer sentences trigger multi-layer expansion.
        is_complex = len(search_query) > 60
        if is_complex:
            print(f"  🔍 Multi-layer retrieval (complex query, {len(search_query)} chars)")
            retrieved_chunks = vector_store.query_multilayer(
                tenant_id=tenant_id,
                text=search_query,
                death_date_ah=req.death_date_ah,
                top_k=config.TOP_K
            )
        else:
            retrieved_chunks = vector_store.query(
                tenant_id=tenant_id,
                text=search_query,
                death_date_ah=req.death_date_ah,
                top_k=config.TOP_K
            )

        # Fallback if search engine yields absolutely zero matched documents
        if not retrieved_chunks:
            return ChatResponse(
                answer_text="I cannot address this query from my documented works.",
                can_answer=False,
                session_id=session_id,
            )

        # Generate grounding-constrained response based on context chunks
        result = llm_client.generate_answer(
            req.query, retrieved_chunks, req.system_prompt, history, intent=intent
        )

        # ── 5. Grounding & Anachronism Verification Check ─────────────
        # Safeguards persona by cross-checking sources and blocking dates after death_date_ah
        if result.get("can_answer") and config.ENABLE_VERIFICATION:
            is_grounded = llm_client.verify_answer(retrieved_chunks, result)
            if not is_grounded:
                result["can_answer"] = False
                result["answer_text"] = "I prefer not to provide an unverified answer, this is beyond my knowledge."
                result["citations"] = []

        # Store historical chat turns in the session database
        session_manager.add_turn(session_id, "user", req.query)
        session_manager.add_turn(session_id, "assistant", result.get("answer_text", ""))
        session_manager.cleanup_expired()

        return ChatResponse(
            answer_text=result["answer_text"],
            can_answer=result["can_answer"],
            citations=[Citation.from_llm(c) for c in result["citations"]],
            follow_up=result["follow_up"],
            closing=result["closing"],
            session_id=session_id,
        )

    except Exception as e:
        logger.error(f"Chat error: {e}", exc_info=True)
        return ChatResponse(
            answer_text="An error occurred while processing your question. Please try again.",
            can_answer=False,
            session_id=session_id,
        )


@app.post("/api/v1/export")
async def export_chat(req: ExportRequest):
    """
    Exports a user session's conversation history.
    Supports either structure-preserving JSON or rich human-readable Markdown format.
    """
    if req.format == "markdown":
        md_text = session_manager.export_session_markdown(req.session_id, "Persona")
        return PlainTextResponse(md_text, media_type="text/markdown")
    else:
        data = session_manager.export_session(req.session_id, "Persona")
        return JSONResponse(data)

